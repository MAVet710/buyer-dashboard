// Keep public metadata aligned with the source-verified walkthroughs.
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
const root = new URL('../', import.meta.url);
const domains = ['retail','production','cultivation','wholesale','operations','compliance'];
const entries = {};
for (const domain of domains) {
  const text = await readFile(new URL(`src/lib/help/${domain}.ts`, root), 'utf8');
  const js = ts.transpileModule(text, {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
  const module = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
  for (const [path, guide] of Object.entries(module[`${domain}Walkthroughs`])) {
    if (entries[path]) throw new Error(`Duplicate help route: ${path}`);
    entries[path] = {title:`${guide.title} | DoobieLogic Help`,description:guide.summary,kind:'article'};
  }
}
const code = '// Generated by scripts/sync-help-metadata.mjs from the detailed guides.\n' +
  'export const helpSeoRoutes: Record<string, { title: string; description: string; kind: "article" }> = ' +
  JSON.stringify(entries, null, 2) + ';\n';
await writeFile(new URL('src/lib/helpSeo.ts', root), code);
console.log(`Help metadata synchronized: ${Object.keys(entries).length} guides.`);
